#!/usr/bin/env python
"""Write the model classes that are combinations of mixins.

Most AstroPhot models are a radial profile (Sersic, Nuker, ...) combined with
one way of laying it out on the sky (plain ellipse, warp, rays, ...). Each of
those pieces is a mixin class, written once in ``astrophot/models/mixins``.
This script writes out every combination as an ordinary class statement, so
that editors and type checkers can see the classes, in the files:

- ``astrophot/models/radial.py``, the galaxy models
- ``astrophot/models/radial_psf.py``, the PSF models

To add a radial profile, write its three mixins (``NameMixin``, ``iNameMixin``
and ``NamePSFMixin``) and add "Name" to `PROFILES` below. To add a way of
perturbing the isophotes, write its mixin and add it to `PERTURBATIONS`. Then
run this script. The pre-commit hook runs it on every commit which touches it
or the files it writes, and ``tests/test_models.py`` checks that the files are
up to date. ``astrophot/models/__init__.py`` exports everything in the two
files, so the new models need no other change to be found as ``ap.models.Name``.

Usage, from anywhere::

    python tools/generate_model_classes.py          # write the files
    python tools/generate_model_classes.py --check  # only say if they are out of date

Only the standard library is used, so that this runs without AstroPhot installed.
"""

import argparse
import sys
from pathlib import Path

MODELS_DIR = Path(__file__).resolve().parent.parent / "astrophot" / "models"

# Radial profiles. "Name" needs NameMixin, iNameMixin and NamePSFMixin in astrophot/models/mixins
PROFILES = ("Sersic", "Exponential", "Gaussian", "Ferrer", "King", "Moffat", "Nuker", "Spline")

# Changes to the shape of the isophotes, as {suffix of the class name: mixin}
PERTURBATIONS = {
    "SuperEllipse": "SuperEllipseMixin",
    "FourierEllipse": "FourierEllipseMixin",
    "Warp": "WarpMixin",
}

HEADER = '''\
# ----------------------------------------------------------------------------
# THIS FILE IS AUTOMATICALLY GENERATED, DO NOT EDIT IT BY HAND.
#
# It is written by tools/generate_model_classes.py and anything changed here is
# overwritten the next time that script runs, which pre-commit does on commit.
# To add, remove or rename a model edit the lists at the top of that script,
# then run:
#
#     python tools/generate_model_classes.py
# ----------------------------------------------------------------------------
"""{doc}"""

'''

LINE_LENGTH = 100  # of black, as it is run for this repository


def galaxy_models():
    """Name and base classes of every galaxy model, in the order they are defined."""
    models = []
    for profile in PROFILES:
        radial = (f"{profile}Mixin", "RadialMixin")
        models.append((f"{profile}Galaxy", (*radial, "GalaxyModel")))
        models.append((f"T{profile}Galaxy", ("TruncationMixin", *radial, "GalaxyModel")))
        for suffix, perturbation in PERTURBATIONS.items():
            bases = (*radial, perturbation, "GalaxyModel")
            models.append((f"{profile}{suffix}", bases))
            models.append((f"T{profile}{suffix}", ("TruncationMixin", *bases)))
    for profile in PROFILES:
        # a separate profile for each segment of the galaxy
        models.append((f"{profile}Ray", (f"i{profile}Mixin", "RayMixin", "GalaxyModel")))
        models.append((f"{profile}Wedge", (f"i{profile}Mixin", "WedgeMixin", "GalaxyModel")))
    return models


def psf_models():
    """Name and base classes of every PSF model, in the order they are defined."""
    models = []
    for profile in PROFILES:
        mixin = f"{profile}PSFMixin"
        models.append((f"{profile}PSF", (mixin, "RadialMixin", "PSFModel")))
        models.append((f"{profile}PSFEllipse", (mixin, "EllipseMixin", "RadialMixin", "PSFModel")))
        for suffix, perturbation in PERTURBATIONS.items():
            bases = (mixin, "InclinedMixin", "RadialMixin", perturbation, "PSFModel")
            models.append((f"{profile}PSF{suffix}", bases))
    return models


def class_statement(name, bases):
    """The first line of a class, split over lines the way black does it."""
    one_line = f"class {name}({', '.join(bases)}):"
    if len(one_line) <= LINE_LENGTH:
        return one_line
    inner = f"    {', '.join(bases)}"
    if len(inner) > LINE_LENGTH:
        inner = "\n".join(f"    {base}," for base in bases)
    return f"class {name}(\n{inner}\n):"


def render(doc, base_model, base_import, models):
    """Source code of a module with the given models."""
    mixins = []
    for _, bases in models:
        mixins.extend(base for base in bases if base != base_model and base not in mixins)
    lines = [
        HEADER.format(doc=doc) + "from .mixins import (",
        *(f"    {mixin}," for mixin in mixins),
        ")",
        base_import,
        "from ..utils.decorators import combine_docstrings",
        "",
        "__all__ = (",
        *(f'    "{name}",' for name, _ in models),
        ")",
    ]
    for name, bases in models:
        lines += [
            "",
            "",
            "@combine_docstrings",
            class_statement(name, bases),
            "    usable = True",
        ]
    return "\n".join(lines) + "\n"


def generated_files():
    """The text of each generated file, by its path."""
    galaxies = render(
        "Galaxy models with a radial brightness profile, every combination of a profile\n"
        "with a shape of the isophotes or a set of rays or wedges.",
        "GalaxyModel",
        "from .galaxy_model_object import GalaxyModel",
        galaxy_models(),
    )
    psfs = render(
        "PSF models with a radial brightness profile, every combination of a profile\n"
        "with a shape of the isophotes.",
        "PSFModel",
        "from .psf_model_object import PSFModel",
        psf_models(),
    )
    return {MODELS_DIR / "radial.py": galaxies, MODELS_DIR / "radial_psf.py": psfs}


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument(
        "--check", action="store_true", help="Change nothing, exit with 1 if a file is out of date"
    )
    args = parser.parse_args(argv)

    stale = []
    for path, text in generated_files().items():
        if path.is_file() and path.read_text(encoding="utf-8") == text:
            continue
        stale.append(path)
        if not args.check:
            # the same line endings on every platform
            with open(path, "w", encoding="utf-8", newline="\n") as file:
                file.write(text)
    for path in stale:
        print(f"{'out of date' if args.check else 'wrote'}: {path}")
    return 1 if stale and args.check else 0


if __name__ == "__main__":
    sys.exit(main())
